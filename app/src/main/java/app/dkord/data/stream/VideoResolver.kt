package app.dkord.data.stream

import app.dkord.core.isLocalAudioId

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.exceptions.AgeRestrictedContentException
import org.schabi.newpipe.extractor.exceptions.ContentNotAvailableException
import org.schabi.newpipe.extractor.exceptions.GeographicRestrictionException
import org.schabi.newpipe.extractor.exceptions.PrivateContentException
import org.schabi.newpipe.extractor.exceptions.ReCaptchaException
import org.schabi.newpipe.extractor.exceptions.SignInConfirmNotBotException
import org.schabi.newpipe.extractor.stream.DeliveryMethod
import java.io.IOException

/** Resolves a muxed video stream plus subtitles through the extractor. Does not touch the audio resolver chain or its cache. */
class VideoResolver {
    suspend fun resolve(videoId: String): ResolvedVideo = withContext(Dispatchers.IO) {
        if (isLocalAudioId(videoId)) throw NoVideoException("Local audio has no provider video")
        try {
            val ex = ServiceList.YouTube.getStreamExtractor("https://www.youtube.com/watch?v=$videoId")
            ex.fetchPage()
            val video = VideoPicker.pick(
                ex.videoStreams.filter { it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP && it.isUrl }
                    .map { VideoCandidate(it.content, it.format?.mimeType ?: "video/mp4", it.height) },
            ) ?: throw NoVideoException("No playable video stream was found for this track. Audio still works.")
            val subs = SubtitlePicker.pick(
                runCatching { ex.subtitlesDefault }.getOrDefault(emptyList()).filter { it.isUrl }.map {
                    SubtitleCandidate(it.content, it.format?.mimeType.orEmpty(), it.languageTag, it.displayLanguageName, it.isAutoGenerated)
                },
            )
            ResolvedVideo(videoId, video, subs, expiryFromUrl(video.url))
        } catch (e: NoVideoException) { throw e
        } catch (e: SignInConfirmNotBotException) { throw StreamError.BotCheck()
        } catch (e: ReCaptchaException) { throw StreamError.BotCheck("(rate limited)")
        } catch (e: AgeRestrictedContentException) { throw StreamError.AgeRestricted()
        } catch (e: PrivateContentException) { throw StreamError.Private()
        } catch (e: GeographicRestrictionException) { throw StreamError.Geo()
        } catch (e: ContentNotAvailableException) { throw StreamError.Unavailable(e.message.orEmpty())
        } catch (e: IOException) { throw StreamError.Network(e)
        } catch (e: org.schabi.newpipe.extractor.exceptions.ExtractionException) {
            throw StreamError.Unavailable("Extractor failed: ${e.message?.lineSequence()?.firstOrNull()}")
        }
    }
}
